import { ERROR_CATALOGUE } from '../common/constants/error-catalogue.js';
import { EVENT_TO_QUEUE_MAP } from '../queue/queue.registry.js';
import { ANALYTICS_EVENT_NAMES } from '../analytics/analytics.service.js';

/**
 * The reference documents that are generated from the code, so they cannot drift from it. A test
 * (`render-docs.spec.ts`) fails when the committed files are out of date; `npm run docs` rewrites them.
 */

const HEADER = '<!-- Generated by `npm run docs`. Do not edit by hand. -->\n';

export function renderErrorCatalogue(): string {
  const rows = Object.entries(ERROR_CATALOGUE)
    .map(([code, entry]) => ({ code, status: Number(entry.status), message: entry.message }))
    .sort((a, b) => a.status - b.status || a.code.localeCompare(b.code));
  const lines = [
    HEADER,
    '# Error code catalogue',
    '',
    'Every error answer has the shape `{ "error": { "code", "message", "details"? }, "requestId" }`. The `code` is stable: clients switch on it, never on the message. The status never changes for a code (one table decides it, `src/common/constants/error-catalogue.ts`).',
    '',
    '| Status | Code | Default message |',
    '|---|---|---|',
    ...rows.map((row) => `| ${row.status} | \`${row.code}\` | ${row.message.replaceAll('|', String.raw`\|`)} |`),
    '',
  ];
  return lines.join('\n');
}

export function renderEventCatalogue(): string {
  const byQueue = new Map<string, string[]>();
  for (const [event, queue] of Object.entries(EVENT_TO_QUEUE_MAP)) {
    byQueue.set(queue, [...(byQueue.get(queue) ?? []), event]);
  }
  const lines = [
    HEADER,
    '# Event catalogue',
    '',
    '## Domain events (the outbox)',
    '',
    'A service writes one outbox row in the same transaction as the change. The publisher puts it on the queue named below, and the worker hands it to every registered handler (notifications, realtime, matching, badges, analytics). A handler must be idempotent: a job can run twice.',
    '',
  ];
  for (const queue of [...byQueue.keys()].sort()) {
    lines.push(`### Queue \`${queue}\``, '', ...(byQueue.get(queue) as string[]).sort().map((event) => `- \`${event}\``), '');
  }
  lines.push(
    '## Analytics events',
    '',
    'Written to `analytics_events` by `AnalyticsEventHandler`, one row per source outbox event. Properties are whitelisted scalars: never an address, a phone number or message text. Raw rows are removed after `ANALYTICS_RETENTION_MONTHS` (13).',
    '',
    ...ANALYTICS_EVENT_NAMES.map((name) => `- \`${name}\``),
    '',
  );
  return lines.join('\n');
}
